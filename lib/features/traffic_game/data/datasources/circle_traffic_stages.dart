/// Helper to build TrafficEntry.
CTTrafficEntry _t(
  String type,
  double at, {
  CTCarRole role = CTCarRole.normal,
  int lap = 0,
}) {
  final vt = _parseType(type);
  return CTTrafficEntry(type: vt, at: at, role: role, lap: lap);
}

CTVehicleType _parseType(String s) {
  switch (s) {
    case 'mini':
      return CTVehicleType.mini;
    case 'van':
      return CTVehicleType.van;
    case 'truck':
      return CTVehicleType.truck;
    case 'bus':
      return CTVehicleType.bus;
    default:
      return CTVehicleType.car;
  }
}

